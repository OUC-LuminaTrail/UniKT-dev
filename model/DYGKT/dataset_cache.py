"""Dataset caching mechanism for DYGKT to avoid repeated preprocessing.

This module provides utilities to cache preprocessed DYGKT datasets,
significantly reducing training start time for repeated runs.
"""

import hashlib
import pickle
from pathlib import Path
import tempfile
from typing import Any

from utils.core import get_logger

logger = get_logger(__name__)


def get_cache_key(args: Any, fold_idx: int | None) -> str:
    """Generate cache key based on dataset and parameters.
    
    Args:
        args: Training arguments
        fold_idx: Fold index for cross-validation
        
    Returns:
        Cache key string (MD5 hash)
    """
    # Internal schema marker for cache compatibility across preprocessing changes.
    cache_schema = "schema2_time64"

    key_parts = [
        cache_schema,
        f"v{getattr(args, 'cache_version', 1)}",
        str(args.dataset),
        str(fold_idx),
        str(getattr(args, "num_neighbor", 50)),
        str(getattr(args, "max_similarity_matrix_questions", 12000)),
        str(getattr(args, "compat_fields", False)),
    ]
    key_str = "_".join(key_parts)
    cache_key = hashlib.md5(key_str.encode()).hexdigest()[:16]
    return f"dygkt_{args.dataset}_fold{fold_idx}_{cache_key}"


def get_cache_dir(base_dir: str | Path | None = None) -> Path:
    """Get cache directory path.
    
    Args:
        base_dir: Base directory for cache (defaults to ./cache/dygkt)
        
    Returns:
        Path to cache directory
    """
    if base_dir is None:
        base_dir = Path("./cache/dygkt")
    else:
        base_dir = Path(base_dir)
    
    base_dir.mkdir(parents=True, exist_ok=True)
    return base_dir


def load_cached_dataset(
    cache_key: str,
    cache_dir: str | Path | None = None,
) -> tuple[Any, Any, Any, dict[str, Any]] | None:
    """Load cached dataset if exists.
    
    Args:
        cache_key: Cache key generated by get_cache_key
        cache_dir: Cache directory path
        
    Returns:
        Tuple of (train_dataset, val_dataset, test_dataset, model_metadata)
        or None if cache doesn't exist
    """
    cache_dir = get_cache_dir(cache_dir)
    cache_file = cache_dir / f"{cache_key}.pkl"
    
    if not cache_file.exists():
        logger.info(f"Cache miss: {cache_key}")
        return None
    
    try:
        logger.info(f"Loading cached dataset from {cache_file}...")
        with open(cache_file, "rb") as f:
            cached_data = pickle.load(f)
        
        logger.info(f"✅ Cache hit: {cache_key} (loaded in {cache_file.stat().st_size / 1024 / 1024:.1f} MB)")
        return cached_data
    except Exception as e:
        logger.warning(f"Failed to load cache {cache_key}: {e}")
        return None


def save_cached_dataset(
    cache_key: str,
    dataset_tuple: tuple[Any, Any, Any, dict[str, Any]],
    cache_dir: str | Path | None = None,
) -> None:
    """Save dataset to cache.
    
    Args:
        cache_key: Cache key generated by get_cache_key
        dataset_tuple: Tuple of (train_dataset, val_dataset, test_dataset, model_metadata)
        cache_dir: Cache directory path
    """
    cache_dir = get_cache_dir(cache_dir)
    cache_file = cache_dir / f"{cache_key}.pkl"
    
    try:
        logger.info(f"Saving dataset to cache: {cache_file}...")
        with tempfile.NamedTemporaryFile("wb", dir=cache_dir, suffix=".tmp", delete=False) as f:
            pickle.dump(dataset_tuple, f, protocol=pickle.HIGHEST_PROTOCOL)
            temp_path = Path(f.name)

        temp_path.replace(cache_file)
        
        size_mb = cache_file.stat().st_size / 1024 / 1024
        logger.info(f"✅ Cached dataset saved: {cache_key} ({size_mb:.1f} MB)")
    except Exception as e:
        logger.warning(f"Failed to save cache {cache_key}: {e}")


def clear_cache(cache_dir: str | Path | None = None, pattern: str = "*.pkl") -> int:
    """Clear cached datasets.
    
    Args:
        cache_dir: Cache directory path
        pattern: File pattern to match (default: *.pkl)
        
    Returns:
        Number of files deleted
    """
    cache_dir = get_cache_dir(cache_dir)
    
    if not cache_dir.exists():
        logger.info("Cache directory doesn't exist, nothing to clear")
        return 0
    
    deleted_count = 0
    total_size = 0
    
    for cache_file in cache_dir.glob(pattern):
        try:
            size = cache_file.stat().st_size
            cache_file.unlink()
            deleted_count += 1
            total_size += size
            logger.debug(f"Deleted cache file: {cache_file.name}")
        except Exception as e:
            logger.warning(f"Failed to delete {cache_file}: {e}")
    
    if deleted_count > 0:
        logger.info(f"✅ Cleared {deleted_count} cache files ({total_size / 1024 / 1024:.1f} MB)")
    else:
        logger.info("No cache files to clear")
    
    return deleted_count
